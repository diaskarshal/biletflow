const messages = { kk, ru, en };
export type Lang = keyof typeof messages;
const LANGS: { code: Lang; label: string }[] = [
    { code: "kk", label: "Қаз" },
    { code: "ru", label: "Рус" },
    { code: "en", label: "Eng" },
];
const LOCALES: Record<Lang, string> = { kk: "kk-KZ", ru: "ru-RU", en: "en-GB" };

let current: Lang = Intl.DateTimeFormat().resolvedOptions().locale.startsWith("ru") ? "ru" : "kk";
const listeners = new Set<() => void>();

SecureStore.getItemAsync("lang").then((saved) => {
    if (saved === "kk" || saved === "ru" || saved === "en") setLang(saved);
});

export function setLang(next: Lang) {
    current = next;
    void SecureStore.setItemAsync("lang", next);
    listeners.forEach((notify) => notify());
}

export function useLang() {
    return useSyncExternalStore(
        (notify) => {
            listeners.add(notify);
            return () => listeners.delete(notify);
        },
        () => current,
    );
}

export function locale() {
    return LOCALES[current];
}

export function t(key: MessageKey, vars?: Record<string, string | number>) {
    const text: string = messages[current][key] ?? en[key];
    return vars ? text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? "")) : text;
}

export function tOptional(key: string): string | undefined {
    return (messages[current] as Record<string, string>)[key];
}

export function LanguageSwitcher() {
    const lang = useLang();
    return (
        <View style={styles.row} accessibilityRole="radiogroup" accessibilityLabel={t("common.language")}>
            {LANGS.map((l) => (
                <Pressable
                    key={l.code}
                    onPress={() => setLang(l.code)}
                    accessibilityRole="radio"
                    accessibilityState={{ selected: lang === l.code }}
                    style={[styles.option, lang === l.code && styles.selected]}
                >
                    <Text style={[styles.label, lang === l.code && styles.selectedLabel]}>{l.label}</Text>
                </Pressable>
            ))}
        </View>
    );
}

const styles = StyleSheet.create({
    row: { flexDirection: "row", gap: 8, justifyContent: "center", marginVertical: 12 },
    option: { borderWidth: 1, borderColor: "#2563eb", borderRadius: 8, paddingVertical: 6, paddingHorizontal: 14 },
    selected: { backgroundColor: "#2563eb" },
    label: { color: "#2563eb", fontWeight: "600" },
    selectedLabel: { color: "#ffffff" },
});
